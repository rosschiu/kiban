-- An empty `[)` window (valid_to = valid_from — assigned and ended on the same day) has no
-- inclusive-inclusive equivalent: valid_to - 1 would violate the CHECK (valid_to >= valid_from)
-- and keeping it as-is would turn "no tenure" into a one-day tenure that collides with a
-- same-day successor under the `[]` exclusion constraint. Such rows are deleted (the audit rows
-- that recorded the assign/end pair remain).
DELETE FROM org.position_assignment WHERE valid_to = valid_from;

UPDATE org.position_assignment SET valid_to = valid_to - 1 WHERE valid_to IS NOT NULL;

ALTER TABLE org.position_assignment
    ADD CONSTRAINT position_assignment_position_id_valid_from_valid_to_excl EXCLUDE USING gist (
        position_id WITH =,
        daterange(valid_from, valid_to, '[]') WITH &&
    );
