func TestExcluded(t *testing.T) {
	excluded := []string{
		"web/sdk/node_modules/x/y.ts",
		"web/node_modules/react/index.js",
		"web/sdk/dist/index.js",
		"coverage/report.html",
		"internal/registry/LICENSE",
		"docs/quickstart.md",            // not a checked extension
		"internal/registry/queries.sql", // wrong ext handled elsewhere; .sql is checked though — remove from excluded list
	}
	// The .md and .sql entries above illustrate two different reasons; re-split below.
	for _, p := range excluded[:6] {
		if !Excluded(p) {
			t.Errorf("Excluded(%q) = false, want true", p)
		}
	}
	if Excluded("internal/registry/queries.sql") {
		t.Errorf("Excluded(%q) = true, want false (.sql is a checked extension, not in an excluded dir)", "internal/registry/queries.sql")
	}

	included := []string{
		"internal/registry/queries.sql",
		"cmd/gateway/main.go",
		"web/sdk/src/index.ts",
		"infra/setup.sh",
	}
	for _, p := range included {
		if Excluded(p) {
			t.Errorf("Excluded(%q) = true, want false", p)
		}
	}
}

func TestHasHeader(t *testing.T) {
	data := []byte("// SPDX-License-Identifier: Apache-2.0\n\npackage foo\n")
	if !HasHeader(data, "// SPDX-License-Identifier: Apache-2.0") {
		t.Error("expected header to be found")
	}
	if HasHeader(data, "// SPDX-License-Identifier: MIT") {
		t.Error("expected mismatched header to not be found")
	}
	if HasHeader([]byte("package foo\n"), "// SPDX-License-Identifier: Apache-2.0") {
		t.Error("expected missing header to not be found")
	}
}

func TestIsGenerated(t *testing.T) {
	gen := []byte("// Code generated by sqlc. DO NOT EDIT.\npackage foo\n")
	if !isGenerated(gen) {
		t.Error("expected generated marker to be detected")
	}
	if isGenerated([]byte("package foo\n")) {
		t.Error("expected non-generated file to not be flagged")
	}
}

func TestInsertHeader_Go(t *testing.T) {
	out := InsertHeader([]byte("package foo\n\nfunc x() {}\n"), ".go", "// SPDX-License-Identifier: Apache-2.0")
	want := "// SPDX-License-Identifier: Apache-2.0\n\npackage foo\n\nfunc x() {}\n"
	if string(out) != want {
		t.Errorf("InsertHeader Go = %q, want %q", out, want)
	}
}

func TestInsertHeader_ShellPreservesShebang(t *testing.T) {
	out := InsertHeader([]byte("#!/usr/bin/env bash\necho hi\n"), ".sh", "# SPDX-License-Identifier: Apache-2.0")
	want := "#!/usr/bin/env bash\n# SPDX-License-Identifier: Apache-2.0\n\necho hi\n"
	if string(out) != want {
		t.Errorf("InsertHeader shell = %q, want %q", out, want)
	}
}

