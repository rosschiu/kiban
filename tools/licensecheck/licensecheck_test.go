func TestWalk_DetectsMissingAndOK(t *testing.T) {
	dir := t.TempDir()
	mustWrite(t, filepath.Join(dir, "cmd", "gateway", "main.go"), "package main\n")
	mustWrite(t, filepath.Join(dir, "cmd", "gateway", "ok.go"), "// SPDX-License-Identifier: Apache-2.0\n\npackage main\n")
	mustWrite(t, filepath.Join(dir, "cmd", "node_modules", "y.go"), "package y\n") // excluded — must never appear
	mustWrite(t, filepath.Join(dir, "cmd", "gateway", "gen.go"), "// Code generated by sqlc. DO NOT EDIT.\npackage main\n")

	findings, err := Walk(dir)
	if err != nil {
		t.Fatalf("Walk: %v", err)
	}
	byPath := map[string]Finding{}
	for _, f := range findings {
		byPath[f.Path] = f
	}
	if byPath["cmd/gateway/main.go"].Status != "missing" {
		t.Errorf("main.go status = %q, want missing", byPath["cmd/gateway/main.go"].Status)
	}
	if byPath["cmd/gateway/ok.go"].Status != "ok" {
		t.Errorf("ok.go status = %q, want ok", byPath["cmd/gateway/ok.go"].Status)
	}
	if byPath["cmd/gateway/gen.go"].Status != "generated-skip" {
		t.Errorf("gen.go status = %q, want generated-skip", byPath["cmd/gateway/gen.go"].Status)
	}
	if _, found := byPath["cmd/node_modules/y.go"]; found {
		t.Error("excluded-directory file must never be visited/reported")
	}
}

func TestFix_InsertsOnlyMissing(t *testing.T) {
	dir := t.TempDir()
	mustWrite(t, filepath.Join(dir, "cmd", "gateway", "main.go"), "package main\n")

	findings, err := Walk(dir)
	if err != nil {
		t.Fatalf("Walk: %v", err)
	}
	n, err := Fix(dir, findings)
	if err != nil {
		t.Fatalf("Fix: %v", err)
	}
	if n != 1 {
		t.Fatalf("Fix inserted %d headers, want 1", n)
	}
	data, err := os.ReadFile(filepath.Join(dir, "cmd", "gateway", "main.go"))
	if err != nil {
		t.Fatal(err)
	}
	if !HasHeader(data, "// SPDX-License-Identifier: Apache-2.0") {
		t.Errorf("fixed file missing expected header:\n%s", data)
	}

	// Re-walking must now report it as "ok", never "missing" again.
	findings2, err := Walk(dir)
	if err != nil {
		t.Fatalf("Walk after fix: %v", err)
	}
	for _, f := range findings2 {
		if f.Path == "cmd/gateway/main.go" && f.Status != "ok" {
			t.Errorf("after Fix, status = %q, want ok", f.Status)
		}
	}
}

func mustWrite(t *testing.T, path, content string) {
	t.Helper()
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(path, []byte(content), 0o644); err != nil {
		t.Fatal(err)
	}
}
