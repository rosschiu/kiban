const (
	quickstartRegistry     = "ghcr.io/rosschiu/"
	quickstartTag          = "${KIBAN_VERSION:?set KIBAN_VERSION in .env}"
	quickstartVolumePrefix = "kiban-quickstart-"
	issuerTLS              = "https://127.0.0.1:${KIBAN_GATEWAY_TLS_HOST_PORT:-8443}"
	issuerHTTP             = "http://localhost:${KIBAN_GATEWAY_HTTP_HOST_PORT:-3000}"
)

var (
	envVarRef      = regexp.MustCompile(`\$\{([A-Z0-9_]+)\}`)
	envExampleLine = regexp.MustCompile(`^([A-Z0-9_]+)=(.*)$`)
	firstPartyImg  = regexp.MustCompile(`^kiban-(\w+):\$\{KIBAN_IMAGE_TAG:-latest\}$`)
	nonWord        = regexp.MustCompile(`\W`)
	publicKeys     = map[string]bool{"KEYCLOAK_ISSUER_URL": true, "KC_HOSTNAME": true, "KC_HOSTNAME_STRICT": true, "KIBAN_DOMAIN": true, "KIBAN_TRUSTED_PROXY": true}
)

const quickstartHeader = `# GENERATED by ` + "`go run ./tools/dev quickstart-compose`" + ` from infra/compose.yaml — do not edit by hand;
# run ` + "`make quickstart-compose`" + ` (checked by ` + "`make docs-freshness-check`" + `). Read README.md first.
#
# Kiban zero-clone quickstart: every image is ` + "`ghcr.io/rosschiu/kiban-<service>:${KIBAN_VERSION}`" + `
# (plus ` + "`postgres:18-alpine`" + `); there is no ` + "`build:`" + ` and no repo checkout. Compared with the source
# file: ` + "`migrate`/`bootstrap`/`keycloak`" + ` ship as GHCR images, ` + "`gateway-devcert`" + ` and the ` + "`test`" + `
# profile fixtures are dropped, the gateway runs its dev-only plain-HTTP listener on host port
# 3000 (no TLS), and the postgres init SQL is inlined as a compose ` + "`config`" + `.
#
# Default port 3000 is deliberate: with no KIBAN_DOMAIN, bootstrap registers only fixed
# dev-loopback redirect URIs (http://localhost:3000, :5173) on the realm, so a browser login only
# completes from that origin. Use the SAME host:port every time you sign in — KEYCLOAK_ISSUER_URL
# is a string compared against the token's ` + "`iss`" + ` claim.
`

const publicHeader = `# GENERATED by ` + "`go run ./tools/dev quickstart-compose --public`" + ` from infra/compose.public.yaml — do not
# edit by hand; run ` + "`make quickstart-compose`" + ` (checked by ` + "`make docs-freshness-check`" + `).
#
# Serve the zero-clone quickstart at a real origin. Put your own TLS-terminating reverse proxy in
# front of the gateway's plain-HTTP host port (3000 by default), set KIBAN_PUBLIC_HOST in .env to
# the hostname it serves (` + "`id.example.com`" + `), and start with both files:
#
#   docker compose -f docker-compose.yml -f compose.public.yaml up -d --wait
#
# The proxy must forward X-Forwarded-Proto and X-Forwarded-Host (Caddy, Traefik and nginx's
# ` + "`proxy_set_header`" + ` do). What changes against docker-compose.yml alone: every token verifier
# expects the public issuer https://$KIBAN_PUBLIC_HOST/realms/<realm>, Keycloak pins its hostname
# to that origin, bootstrap registers the realm's redirect URIs for it (KIBAN_DOMAIN) and the
# gateway trusts the edge's forwarded headers (KIBAN_TRUSTED_PROXY). Re-run ` + "`bootstrap`" + ` once after
# first adding this file to an existing stack so the realm client picks up the new origin.
`

// runQuickstartCompose is `make quickstart-compose`: deploy/quickstart/docker-compose.yml from
// infra/compose.yaml on stdout. The transformation is the zero-clone shape: no `build:`, GHCR
// images pinned by ${KIBAN_VERSION}, no dev-only services (profiles, the devcert one-shot),
// the gateway in plain-HTTP mode, env defaults from deploy/quickstart/.env.example, and the
// postgres init SQL inlined as a compose `config`.
//
// --public instead generates compose.public.yaml from infra/compose.public.yaml: the overlay
// that serves the published images at a real origin. Only the origin-dependent settings are
// carried over (issuer, Keycloak hostname, KIBAN_DOMAIN, trusted proxy, restart policies).
func runQuickstartCompose(args []string) int {
	public := false
	switch {
	case len(args) == 0:
	case len(args) == 1 && args[0] == "--public":
		public = true
	default:
		fmt.Fprintln(os.Stderr, "usage: dev quickstart-compose [--public]")
		return 2
	}
	defaults, err := envExampleDefaults("deploy/quickstart/.env.example")
	if err != nil {
		return fail("quickstart-compose", err)
	}
	src, err := loadYAML("infra/compose.yaml")
	if err != nil {
		return fail("quickstart-compose", err)
	}
	services := mapGet(src, "services")
	if services == nil {
		return fail("quickstart-compose", errors.New("infra/compose.yaml has no services"))
	}
	rewrite := func(s string) string {
		s = strings.ReplaceAll(s, issuerTLS, issuerHTTP)
		return envVarRef.ReplaceAllStringFunc(s, func(m string) string {
			v := m[2 : len(m)-1]
			d, ok := defaults[v]
			if !ok {
				return m
			}
			if d == "" {
				return "${" + v + ":?set a strong value in .env}"
			}
			return "${" + v + ":-" + d + "}"
		})
	}

	var doc *yaml.Node
	var header string
	if public {
		header = publicHeader
		overlay, err := loadYAML("infra/compose.public.yaml")
		if err != nil {
			return fail("quickstart-compose", err)
		}
		kept := map[string]bool{}
		for _, name := range mapKeys(services) {
			if mapGet(mapGet(services, name), "profiles") == nil {
				kept[name] = true
			}
		}
		out := newMap()
		for _, name := range mapKeys(mapGet(overlay, "services")) {
			if !kept[name] {
				continue
			}
			s := mapGet(mapGet(overlay, "services"), name)
			o := newMap()
			if r := mapGet(s, "restart"); r != nil {
				mapSet(o, "restart", r)
			}
			if env := mapGet(s, "environment"); env != nil {
				e := newMap()
				for _, k := range mapKeys(env) {
					if publicKeys[k] {
						mapSet(e, k, mapGet(env, k))
					}
				}
				if len(e.Content) > 0 {
					mapSet(o, "environment", e)
				}
			}
			if len(o.Content) > 0 {
				mapSet(out, name, o)
			}
		}
		doc = newMap()
		mapSet(doc, "services", out)
	} else {
		header = quickstartHeader
		// Dev-only services: profile-gated fixtures, and the self-signed-cert one-shot (the
		// quickstart gateway runs in plain-HTTP mode).
		dropped := map[string]bool{"gateway-devcert": true}
		for _, name := range mapKeys(services) {
			if mapGet(mapGet(services, name), "profiles") != nil {
				dropped[name] = true
			}
		}
		// ...and the named volumes they shared with a kept service (the devcert's TLS volume).
		droppedVols := map[string]bool{}
		for name := range dropped {
			for _, v := range seqStrings(mapGet(mapGet(services, name), "volumes")) {
				droppedVols[strings.SplitN(v, ":", 2)[0]] = true
			}
		}
		srcVolumes := map[string]bool{}
		for _, v := range mapKeys(mapGet(src, "volumes")) {
			srcVolumes[v] = true
		}
		configs := newMap()
		kept := newMap()
		for _, name := range mapKeys(services) {
			if dropped[name] {
				continue
			}
			s := mapGet(services, name)
			mapDel(s, "build")
			// Compose secrets are not carried over: the quickstart keeps the plain `<VAR>` env
			// var for every `<VAR>_FILE` that pointed at one (its documented weaker posture).
			mapDel(s, "secrets")
			if env := mapGet(s, "environment"); env != nil {
				for _, k := range mapKeys(env) {
					if strings.HasSuffix(k, "_FILE") && strings.HasPrefix(scalar(mapGet(env, k)), "/run/secrets/") {
						mapDel(env, k)
						base := strings.TrimSuffix(k, "_FILE")
						mapSet(env, base, strNode("${"+base+"}"))
					}
				}
			}
			if img := mapGet(s, "image"); img != nil {
				if m := firstPartyImg.FindStringSubmatch(img.Value); m != nil {
					img.Value = quickstartRegistry + "kiban-" + m[1] + ":" + quickstartTag
				}
			}
			if dep := mapGet(s, "depends_on"); dep != nil {
				for d := range dropped {
					mapDel(dep, d)
				}
			}
			// Env values that name a dropped service point at nothing on purpose (the
			// notification worker's SMTP host: it logs and retries instead of crashing).
			if env := mapGet(s, "environment"); env != nil {
				for _, k := range mapKeys(env) {
					if v := mapGet(env, k); v.Kind == yaml.ScalarNode && dropped[v.Value] {
						v.Value = "localhost"
					}
				}
			}
			if vols := mapGet(s, "volumes"); vols != nil {
				var keep []*yaml.Node
				for _, v := range vols.Content {
					host := strings.SplitN(v.Value, ":", 2)[0]
					switch {
					case droppedVols[host]:
					case srcVolumes[host]:
						keep = append(keep, strNode(quickstartVolumePrefix+strings.TrimPrefix(v.Value, "kiban-")))
					case host == "./postgres-init":
						// A zero-clone checkout has no repo file to bind-mount: inline each init file.
						files, err := filepath.Glob("infra/postgres-init/*")
						if err != nil {
							return fail("quickstart-compose", err)
						}
						sort.Strings(files)
						cfgs := newSeq()
						for _, f := range files {
							data, err := os.ReadFile(f)
							if err != nil {
								return fail("quickstart-compose", err)
							}
							stem := strings.TrimSuffix(filepath.Base(f), filepath.Ext(f))
							key := nonWord.ReplaceAllString(stem, "_")
							content := newMap()
							mapSet(content, "content", literalNode(string(data)))
							mapSet(configs, key, content)
							ref := newMap()
							mapSet(ref, "source", strNode(key))
							mapSet(ref, "target", strNode("/docker-entrypoint-initdb.d/"+filepath.Base(f)))
							cfgs.Content = append(cfgs.Content, ref)
						}
						if existing := mapGet(s, "configs"); existing != nil {
							existing.Content = append(existing.Content, cfgs.Content...)
						} else {
							mapSet(s, "configs", cfgs)
						}
					default:
						keep = append(keep, v)
					}
				}
				if len(keep) > 0 {
					vols.Content = keep
				} else {
					mapDel(s, "volumes")
				}
			}
			mapSet(kept, name, s)
		}
		// The gateway runs its dev-only plain-HTTP listener (:8090): no devcert image, no
		// domain for a real TLS mode. Same mode infra/compose.public.yaml uses behind a proxy.
		gw := mapGet(kept, "gateway")
		if gw == nil {
			return fail("quickstart-compose", errors.New("no gateway service"))
		}
		env := mapGet(gw, "environment")
		mapSet(env, "KIBAN_TLS_CERT_FILE", strNode(""))
		mapSet(env, "KIBAN_TLS_KEY_FILE", strNode(""))
		mapSet(env, "KIBAN_INSECURE_HTTP", strNode("true"))
		if ports := mapGet(gw, "ports"); ports != nil {
			var keep []*yaml.Node
			for _, p := range ports.Content {
				if strings.HasSuffix(p.Value, ":8090") {
					keep = append(keep, strNode(strings.ReplaceAll(p.Value, ":-8090}", ":-3000}")))
				}
			}
			ports.Content = keep
		}
		if hc := mapGet(mapGet(gw, "healthcheck"), "test"); hc != nil {
			for _, t := range hc.Content {
				t.Value = strings.ReplaceAll(strings.ReplaceAll(t.Value, "curl -sk", "curl -s"), "https://127.0.0.1:8443/", "http://127.0.0.1:8090/")
			}
		}
		used := map[string]bool{}
		for _, name := range mapKeys(kept) {
			for _, v := range seqStrings(mapGet(mapGet(kept, name), "volumes")) {
				if host := strings.SplitN(v, ":", 2)[0]; strings.HasPrefix(host, quickstartVolumePrefix) {
					used[host] = true
				}
			}
		}
		usedNames := make([]string, 0, len(used))
		for v := range used {
			usedNames = append(usedNames, v)
		}
		sort.Strings(usedNames)
		volumes := newMap()
		for _, v := range usedNames {
			mapSet(volumes, v, newMap())
		}
		doc = newMap()
		mapSet(doc, "services", kept)
		mapSet(doc, "volumes", volumes)
		mapSet(doc, "configs", configs)
	}
	walkScalars(doc, func(n *yaml.Node) {
		if n.Tag == "" || n.Tag == "!!str" {
			n.Value = rewrite(n.Value)
		}
	})
	var buf bytes.Buffer
	buf.WriteString(header)
	enc := yaml.NewEncoder(&buf)
	enc.SetIndent(2)
	if err := enc.Encode(doc); err != nil {
		return fail("quickstart-compose", err)
	}
	if err := enc.Close(); err != nil {
		return fail("quickstart-compose", err)
	}
	os.Stdout.Write(buf.Bytes())
	return 0
}

// envExampleDefaults reads `VAR=value` lines; a blank value means the user must set it.
func envExampleDefaults(path string) (map[string]string, error) {
	data, err := os.ReadFile(path)
	if err != nil {
		return nil, err
	}
	out := map[string]string{}
	for _, line := range strings.Split(string(data), "\n") {
		if m := envExampleLine.FindStringSubmatch(strings.TrimRight(line, "\r")); m != nil {
			out[m[1]] = m[2]
		}
	}
	return out, nil
}

// --- yaml.Node helpers: order-preserving mapping access ---------------------------------

func loadYAML(path string) (*yaml.Node, error) {
	data, err := os.ReadFile(path)
	if err != nil {
		return nil, err
	}
	var doc yaml.Node
	if err := yaml.Unmarshal(data, &doc); err != nil {
		return nil, fmt.Errorf("%s: %w", path, err)
	}
	root := &doc
	if doc.Kind == yaml.DocumentNode && len(doc.Content) == 1 {
		root = doc.Content[0]
	}
	return flatten(root), nil
}

// flatten resolves every alias into a copy of its anchor's node and drops anchors and
// comments, so the tree can be cut and reordered freely (a dropped service may own the anchor
// a kept one references) and the output carries no source comments. The result is what a
// plain data load would have produced.
func flatten(n *yaml.Node) *yaml.Node {
	if n == nil {
		return nil
	}
	if n.Kind == yaml.AliasNode {
		return flatten(n.Alias)
	}
	out := *n
	out.Anchor, out.HeadComment, out.LineComment, out.FootComment = "", "", "", ""
	out.Content = make([]*yaml.Node, len(n.Content))
	for i, c := range n.Content {
		out.Content[i] = flatten(c)
	}
	return &out
}

func newMap() *yaml.Node { return &yaml.Node{Kind: yaml.MappingNode, Tag: "!!map"} }
func newSeq() *yaml.Node { return &yaml.Node{Kind: yaml.SequenceNode, Tag: "!!seq"} }
func strNode(s string) *yaml.Node {
	return &yaml.Node{Kind: yaml.ScalarNode, Tag: "!!str", Value: s}
}

// literalNode is a multi-line string as a `|` block (the inlined SQL).
func literalNode(s string) *yaml.Node {
	n := strNode(s)
	if strings.Contains(s, "\n") && !strings.Contains(s, "\r") {
		n.Style = yaml.LiteralStyle
	}
	return n
}

func mapGet(m *yaml.Node, key string) *yaml.Node {
	if m == nil || m.Kind != yaml.MappingNode {
		return nil
	}
	for i := 0; i+1 < len(m.Content); i += 2 {
		if m.Content[i].Value == key {
			return m.Content[i+1]
		}
	}
	return nil
}

func mapSet(m *yaml.Node, key string, v *yaml.Node) {
	for i := 0; i+1 < len(m.Content); i += 2 {
		if m.Content[i].Value == key {
			m.Content[i+1] = v
			return
		}
	}
	m.Content = append(m.Content, strNode(key), v)
}

func mapDel(m *yaml.Node, key string) {
	if m == nil || m.Kind != yaml.MappingNode {
		return
	}
	for i := 0; i+1 < len(m.Content); i += 2 {
		if m.Content[i].Value == key {
			m.Content = append(m.Content[:i], m.Content[i+2:]...)
			return
		}
	}
}

func mapKeys(m *yaml.Node) []string {
	if m == nil || m.Kind != yaml.MappingNode {
		return nil
	}
	keys := make([]string, 0, len(m.Content)/2)
	for i := 0; i+1 < len(m.Content); i += 2 {
		keys = append(keys, m.Content[i].Value)
	}
	return keys
}

func seqStrings(s *yaml.Node) []string {
	if s == nil || s.Kind != yaml.SequenceNode {
		return nil
	}
	out := make([]string, 0, len(s.Content))
	for _, n := range s.Content {
		out = append(out, n.Value)
	}
	return out
}

func scalar(n *yaml.Node) string {
	if n == nil {
		return ""
	}
	return n.Value
}

func walkScalars(n *yaml.Node, f func(*yaml.Node)) {
	if n == nil {
		return
	}
	if n.Kind == yaml.ScalarNode {
		f(n)
		return
	}
	for _, c := range n.Content {
		walkScalars(c, f)
	}
}
