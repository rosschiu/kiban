#!/usr/bin/env bash
# SPDX-License-Identifier: Apache-2.0
# The one operator script for the Kustomize deployment. Runs where only kubectl exists.
#
#   deploy/k8s/kiban.sh secrets <kind|production>              write-once Secret generator
#   deploy/k8s/kiban.sh apply   <kind|production> [namespace]  staged apply + kubectl wait
#
# secrets: writes overlays/<overlay>/secret.yaml (gitignored, 0600) with a strong value for
# every field base/secret.example.yaml ships as `REPLACE_ME`, in the kiban namespace. Write-once:
# an existing file is left exactly as-is; delete it yourself to get a fresh set. Upgrading from
# 0.1.0, where the base listed base/secret.yaml: that file is MOVED into the overlay unchanged,
# so the cluster's Secret is not re-issued.
#
# apply: kubectl apply -k the overlay, then wait in compose's own depends_on order: postgres,
# keycloak, the migrate Job, the bootstrap Job, then every Deployment the overlay created. The
# migrate/bootstrap Jobs are deleted first on a re-run (a Job's pod template is immutable, and a
# leftover Complete Job would satisfy the waits without the new version's migrations running).
set -euo pipefail
script_dir="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
cmd="${1:-}"
overlay="${2:-}"
usage() { echo "usage: kiban.sh secrets <kind|production> | kiban.sh apply <kind|production> [namespace]" >&2; exit 2; }
[ -n "$cmd" ] && [ -n "$overlay" ] || usage
overlay_dir="$script_dir/overlays/$overlay"
[ -d "$overlay_dir" ] || { echo "[kiban] FAIL: no such overlay: $overlay_dir" >&2; exit 1; }

secrets() {
  local example_file="$script_dir/base/secret.example.yaml"
  local out_file="$overlay_dir/secret.yaml"
  local legacy_file="$script_dir/base/secret.yaml"
  log() { echo "[secrets] $*" >&2; }
  [ -f "$example_file" ] || { echo "[secrets] FAIL: $example_file not found" >&2; exit 1; }
  if [ -f "$legacy_file" ] && [ ! -f "$out_file" ]; then
    mv "$legacy_file" "$out_file"
    log "moved 0.1.0's $legacy_file to $out_file (values unchanged; the base no longer lists it)"
  fi
  if [ -f "$out_file" ]; then
    log "$out_file already exists — leaving every value exactly as-is (write-once; never regenerated)"
    log "delete it yourself first if you really want a fresh secret set (e.g. after a full cluster teardown)"
    return 0
  fi
  log "generating $out_file from $example_file's field list"
  {
    echo "# Generated by deploy/k8s/kiban.sh secrets — DO NOT COMMIT (gitignored)."
    echo "# Real credentials. Re-run only after deleting this file on purpose."
    echo "apiVersion: v1"
    echo "kind: Secret"
    echo "metadata:"
    echo "  name: kiban-secrets"
    echo "  namespace: kiban"
    echo "type: Opaque"
    echo "stringData:"
    while IFS= read -r key; do
      value="$(openssl rand -hex 24)"
      echo "  ${key}: \"${value}\""
      log "generated ${key}"
    done < <(sed -n 's/^  \([A-Za-z0-9_-]*\): "REPLACE_ME"$/\1/p' "$example_file")
  } > "$out_file"
  chmod 600 "$out_file"
  log "done — $out_file written (0600). Apply with: deploy/k8s/kiban.sh apply $overlay"
}

apply() {
  local ns="${3:-kiban}"
  log() { echo "[apply] $*"; }
  [ -f "$overlay_dir/secret.yaml" ] || { echo "[apply] FAIL: $overlay_dir/secret.yaml missing — run deploy/k8s/kiban.sh secrets $overlay first" >&2; exit 1; }
  command -v kubectl >/dev/null 2>&1 || { echo "[apply] FAIL: kubectl not on PATH" >&2; exit 1; }
  if kubectl get namespace "$ns" >/dev/null 2>&1; then
    log "removing previous migrate/bootstrap Jobs (immutable spec; they rerun below)"
    kubectl -n "$ns" delete job migrate bootstrap --ignore-not-found --wait=true
  fi
  log "applying full manifest set (overlay: $overlay, namespace: $ns)"
  kubectl apply -k "$overlay_dir"
  log "stage 1 wait: postgres ready"
  kubectl -n "$ns" rollout status statefulset/postgres --timeout=180s
  log "stage 1 wait: keycloak ready"
  kubectl -n "$ns" rollout status deployment/keycloak --timeout=300s
  log "stage 2 wait: migrate Job complete"
  kubectl -n "$ns" wait --for=condition=complete job/migrate --timeout=600s
  log "stage 3 wait: bootstrap Job complete"
  kubectl -n "$ns" wait --for=condition=complete job/bootstrap --timeout=600s
  log "stage 4 wait: app services ready"
  local svc
  for svc in registry identity org authz notification timesheet docs helpdesk gateway; do
    if kubectl -n "$ns" get deployment/"$svc" >/dev/null 2>&1; then
      kubectl -n "$ns" rollout status deployment/"$svc" --timeout=180s
    else
      log "stage 4 wait: $svc not deployed by this overlay — skipped"
    fi
  done
  log "done — every workload ready. Try: kubectl -n $ns port-forward svc/gateway 8090:8090"
}

case "$cmd" in
  secrets) secrets ;;
  apply) apply "$@" ;;
  *) usage ;;
esac
